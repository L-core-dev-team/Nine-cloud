import { randomUUID } from 'node:crypto';
import { Pool } from 'pg';
import { afterAll, describe, expect, it } from 'vitest';
import { createApp } from '../app.js';
import { sessionToken } from '../routes/auth.js';
import { EmailAuthService } from './email-auth.js';
import { PostgresEmailAuthRepository } from './postgres-email-auth.js';
import { CloudSaveService } from './cloud-save-service.js';
import { PostgresCloudSaveRepository } from './postgres-cloud-save-repository.js';

const suite = process.env.TEST_DATABASE_URL ? describe : describe.skip;
suite('PostgreSQL email sessions and cloud ownership', () => {
  const pool = new Pool({ connectionString: process.env.TEST_DATABASE_URL, max: 4, connectionTimeoutMillis: 3000 });
  const prefix = randomUUID(); const emails = ['a', 'b', 'attempts', 'limits', 'expired'].map(name => `${name}-${prefix}@example.invalid`);
  const saveId = `auth-${prefix}`; const sent = new Map<string, string>(); let now = new Date();
  const repository = new PostgresEmailAuthRepository(pool);
  const service = new EmailAuthService(repository, async (email, code) => { sent.set(email, code); }, 'integration-only-secret'.repeat(3), () => now);
  const origin = 'https://game.example.invalid';
  const app = createApp(undefined, {
    service: new CloudSaveService(new PostgresCloudSaveRepository(pool)),
    auth: { resolveOwnerId: async request => (await service.resolve(sessionToken(request)))?.ownerId ?? null },
  }, { service, origin });
  const post = (path: string, body: unknown, cookie = '') => app.request(path, {
    method: 'POST', headers: { origin, cookie, 'content-type': 'application/json' }, body: JSON.stringify(body),
  });
  const get = (path: string, cookie = '') => app.request(path, { headers: { cookie } });
  afterAll(async () => {
    // Only IDs generated by this test are removed from the dedicated test database.
    { const client = await pool.connect(); try { await client.query('BEGIN'); await client.query("SELECT set_config('jiuxiao.account_erasure_operation','test-cleanup',true)"); await client.query('DELETE FROM game_saves WHERE id = $1', [saveId]); await client.query('COMMIT'); } catch (error) { await client.query('ROLLBACK'); throw error; } finally { client.release(); } }
    await pool.query('DELETE FROM auth_accounts WHERE email = ANY($1::text[])', [emails]);
    await pool.query('DELETE FROM auth_challenges WHERE email = ANY($1::text[])', [emails]);
    await pool.end();
  });
  it('single-use login, concurrent refresh, logout and two accounts cannot cross-read/write', async () => {
    const cookies: string[] = []; const owners: string[] = [];
    for (const email of emails.slice(0, 2)) {
      expect((await post('/api/auth/code', { email })).status).toBe(202);
      const responses = await Promise.all([post('/api/auth/verify', { email, code: sent.get(email) }), post('/api/auth/verify', { email, code: sent.get(email) })]);
      expect(responses.map(r => r.status).sort()).toEqual([200, 401]);
      const response = responses.find(r => r.status === 200)!;
      cookies.push(response.headers.get('set-cookie')!.split(';')[0]!); owners.push((await response.json()).account.id);
    }
    expect(owners[0]).not.toBe(owners[1]);
    const initial = { schemaVersion: 1, saveId, canonVersion: 'test-canon', ruleVersion: 'test-rule', memoryPolicyVersion: 'test-memory', revision: 0,
      state: { playerId: 'test-player', locationId: 'gate', elapsedMinutes: 0, facts: { archiveKind: 'local-untrusted-v1', localArchive: { name: '测试备份' } } } };
    expect((await get('/api/saves')).status).toBe(401);
    expect((await post('/api/saves', { save: initial, ownerId: owners[1] }, cookies[0])).status).toBe(201);
    expect((await get(`/api/saves/${saveId}`, cookies[1])).status).toBe(404);
    expect(await (await get('/api/saves', cookies[1])).json()).toEqual({ saves: [] });
    expect((await app.request(`/api/saves/${saveId}`, { method: 'PUT', headers: { origin, cookie: cookies[1]!, 'content-type': 'application/json' },
      body: JSON.stringify({ expectedRevision: 0, save: { ...initial, revision: 1 } }) })).status).toBe(404);
    expect((await get(`/api/saves/${saveId}`, cookies[0])).status).toBe(200);
    expect(await (await get('/api/save-index?limit=1', cookies[0])).json()).toEqual({ saves: [{ saveId, name: '测试备份', revision: 0 }], hasMore: false });
    expect(await (await get('/api/save-index', cookies[1])).json()).toEqual({ saves: [], hasMore: false });
    expect((await get('/api/save-index?limit=51', cookies[0])).status).toBe(400);
    expect((await app.request('/api/saves', { headers: { cookie: cookies[1]!, 'x-jiuxiao-account': owners[0]! } })).status).toBe(401);
    const refreshes = await Promise.all([post('/api/auth/refresh', {}, cookies[0]), post('/api/auth/refresh', {}, cookies[0])]);
    expect(refreshes.map(r => r.status).sort()).toEqual([200, 401]);
    const next = refreshes.find(r => r.status === 200)!.headers.get('set-cookie')!.split(';')[0]!;
    expect((await get('/api/saves', cookies[0])).status).toBe(401);
    expect((await post('/api/auth/logout', {}, next)).status).toBe(200);
    expect((await get('/api/saves', next)).status).toBe(401);
    expect((await get('/api/auth/session', cookies[1])).status).toBe(200);
    const stored = await pool.query('SELECT token_hash FROM auth_sessions WHERE owner_id = $1', [owners[1]]);
    expect(stored.rows[0].token_hash).toMatch(/^[a-f0-9]{64}$/);
    expect(stored.rows[0].token_hash).not.toBe(cookies[1]!.split('=')[1]);
  });
  it('five guesses exhaust a code, expiry rejects it and six-per-hour resending persists', async () => {
    const email = emails[2]!; await service.requestCode(email); const code = sent.get(email)!;
    const wrong = code === '000000' ? '111111' : '000000';
    await Promise.all(Array.from({ length: 5 }, () => service.verify(email, wrong)));
    expect(await service.verify(email, code)).toBeNull();
    expect((await pool.query('SELECT attempts FROM auth_challenges WHERE email = $1', [email])).rows[0].attempts).toBe(5);
    const limitEmail = emails[3]!;
    for (let i = 0; i < 6; i++) { expect(await service.requestCode(limitEmail)).toBe('sent'); now = new Date(now.getTime() + 60000); }
    expect(await service.requestCode(limitEmail)).toBe('limited');
    now = new Date(now.getTime() + 3600000); expect(await service.requestCode(limitEmail)).toBe('sent');
    const expiredEmail = emails[4]!; await service.requestCode(expiredEmail); now = new Date(now.getTime() + 600000);
    expect(await service.verify(expiredEmail, sent.get(expiredEmail))).toBeNull();
  });
  it('a failed old delivery cannot invalidate a newer code', async () => {
    const email = emails[4]!; now = new Date(now.getTime() + 60000);
    const oldDigest = 'a'.repeat(64), nextDigest = 'b'.repeat(64);
    expect(await repository.issue(email, oldDigest, now, new Date(now.getTime() + 600000))).toBe(true);
    now = new Date(now.getTime() + 60000);
    expect(await repository.issue(email, nextDigest, now, new Date(now.getTime() + 600000))).toBe(true);
    await repository.invalidate(email, oldDigest);
    expect((await pool.query('SELECT digest FROM auth_challenges WHERE email = $1', [email])).rows[0].digest).toBe(nextDigest);
  });
});
